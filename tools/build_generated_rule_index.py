#!/usr/bin/env python3
"""Index the validated rule pool by subject and by scene."""
from __future__ import annotations

import json
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE))

SOURCE = BASE / "resources" / "generated_rules.json"
TARGET = BASE / "generated_rules.py"

SCENE_OF_FAMILY = {
    "SCAFFOLD": "SCAFFOLD_FAMILY",
    "LIFTING": "LIFTING_FAMILY",
    "ELECTRICITY": "TEMPORARY_ELECTRICITY",
    "PIT": "FOUNDATION_PIT",
    "HEIGHT": "WORK_AT_HEIGHT",
    "GENERAL": "GENERAL_SITE",
}


def main() -> int:
    if not SOURCE.exists():
        print(f"没有 {SOURCE}，先跑 validate_generated_rules.py", file=sys.stderr)
        return 1
    from scene_checklists import SUBJECT_CHECKLIST

    families_of = {group["subject"]: (group.get("families") or ["GENERAL"])[0]
                    for group in SUBJECT_CHECKLIST}
    rules = json.loads(SOURCE.read_text(encoding="utf-8"))
    by_subject: dict[str, list[dict]] = {}
    for rule in rules:
        by_subject.setdefault(rule.get("subject") or "", []).append(rule)

    by_scene: dict[str, list[dict]] = {}
    for subject, items in by_subject.items():
        for family in families_of.get(subject, ["GENERAL"]):
            scene = SCENE_OF_FAMILY.get(family, "GENERAL_SITE")
            by_scene.setdefault(scene, []).extend(items)

    lines = [
        '"""Generated rules indexed by subject and by scene.',
        "",
        "Generated by tools/build_generated_rule_index.py from the validated rule",
        "pool. These rules extend the hand-curated rule pack with clauses that",
        "were not turned into rules by hand. They are opt-in: set",
        "USE_GENERATED_RULES=1 to add them to the checklist, and keep the prompt",
        "budget in mind when doing so.",
        '"""',
        "",
        "from typing import Any",
        "",
        "GENERATED_BY_SUBJECT: dict[str, list[dict[str, Any]]] = {",
    ]
    for subject, items in sorted(by_subject.items()):
        lines.append(f"    {subject!r}: [")
        for item in items:
            lines.append(f"        {item!r},")
        lines.append("    ],")
    lines.append("}")
    lines.append("")
    lines.append("GENERATED_BY_SCENE: dict[str, list[dict[str, Any]]] = {")
    for scene, items in sorted(by_scene.items()):
        lines.append(f"    {scene!r}: [")
        for item in items:
            lines.append(f"        {item!r},")
        lines.append("    ],")
    lines.append("}")
    lines.append("")
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"写入 {TARGET}：{len(by_subject)} 个主体，{len(by_scene)} 个场景，{len(rules)} 条规则")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
