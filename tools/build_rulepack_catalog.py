#!/usr/bin/env python3
"""Generate the rule-pack catalogue from data/rulepack/rulepack_snapshot.json.

The snapshot is the group's own rule pack (rulepack.sqlite3). Every generated
record keeps the standard code, clause number and clause text exactly as the
rule pack stores them, and records that they were imported from the project
rule pack rather than from an official publication.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
SNAPSHOT = BASE / "data" / "rulepack" / "rulepack_snapshot.json"
TARGET = BASE / "src" / "catalogs" / "rulepack_catalog.py"

ALL_SCENES = [
    "GENERAL_SITE", "TEMPORARY_ELECTRICITY", "WORK_AT_HEIGHT", "FOUNDATION_PIT",
    "LIFTING_OPERATIONS", "TOWER_CRANE", "CONSTRUCTION_HOIST",
    "SCAFFOLD_COUPLER_TYPE", "SCAFFOLD_DISC_BUCKLE",
    "SCAFFOLD_CANTILEVER", "SCAFFOLD_ATTACHED_LIFTING",
]

# rulepack_id 前缀 / 标准号 -> 适用场景键。前缀沿用规则包自身的命名。
PREFIX_SCENES = [
    ("SCAFFOLD-CANTILEVER", ["SCAFFOLD_CANTILEVER"]),
    ("SCAFFOLD-COUPLER", ["SCAFFOLD_COUPLER_TYPE"]),
    ("SCAFFOLD-DISC-BUCKLE", ["SCAFFOLD_DISC_BUCKLE"]),
    ("SCAFFOLD-ATTACHED-LIFTING", ["SCAFFOLD_ATTACHED_LIFTING"]),
    ("DGTJ08", ["SCAFFOLD_CANTILEVER"]),
    ("JGJ130", ["SCAFFOLD_COUPLER_TYPE"]),
    ("JGJ231", ["SCAFFOLD_DISC_BUCKLE"]),
    ("JGJ202", ["SCAFFOLD_ATTACHED_LIFTING"]),
    ("GB5144", ["TOWER_CRANE"]),
    ("GBT5031", ["TOWER_CRANE"]),
    ("GB10055", ["CONSTRUCTION_HOIST"]),
    ("GBT34023", ["CONSTRUCTION_HOIST"]),
    ("GB50194", ["TEMPORARY_ELECTRICITY"]),
    ("JGJ276", ["LIFTING_OPERATIONS"]),
    ("JGJ311", ["FOUNDATION_PIT"]),
    ("JGJ80", ["WORK_AT_HEIGHT"]),
    ("JGJ184", ALL_SCENES),
]


def scenes_for(rulepack_id: str) -> list[str]:
    for prefix, scenes in PREFIX_SCENES:
        if rulepack_id.startswith(prefix) or f"-{prefix}-" in rulepack_id or f"@{prefix}" in rulepack_id:
            return list(scenes)
    for prefix, scenes in PREFIX_SCENES:
        if prefix in rulepack_id:
            return list(scenes)
    return ["GENERAL_SITE"]


def slug(rulepack_id: str) -> str:
    tail = rulepack_id.split("@")[-1]
    return re.sub(r"[^0-9A-Za-z]+", "_", tail).strip("_").upper()


def triggers_for(rule) -> list[dict]:
    """Keep the subject anchors of the rule pack.

    A trigger names one observable subject in the photo and the cues that tell
    the model how to recognise it. The fast checker renders the trigger name
    in front of a checklist line so the model knows where to look, which the
    dimension text alone does not say.
    """
    out = []
    for trigger in rule.get("triggers") or []:
        name = str(trigger.get("trigger_name") or "").strip()
        if not name:
            continue
        out.append({
            "trigger_id": str(trigger.get("trigger_id") or "").strip(),
            "trigger_name": name,
            "visibility_tag": str(trigger.get("visibility_tag") or "").strip(),
            "recognition_mode": str(trigger.get("recognition_mode") or "").strip(),
            "observable_cues": [str(c).strip() for c in trigger.get("observable_cues") or [] if str(c).strip()],
        })
    return out


def aliases_for(rule) -> list[str]:
    out = []
    for value in rule.get("similar_words") or []:
        if value and len(value) >= 2:
            out.append(str(value))
    for value in rule.get("keywords") or []:
        if value and len(value) >= 2:
            out.append(str(value))
    for trigger in rule.get("triggers") or []:
        name = str(trigger.get("trigger_name") or "")
        if len(name) >= 2:
            out.append(name)
    seen, unique = set(), []
    for value in out:
        if value not in seen:
            seen.add(value)
            unique.append(value)
    return unique


def main() -> int:
    snapshot = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    rules = snapshot["rules"]
    database = snapshot.get("source_database", "")
    database_sha = snapshot.get("source_database_sha256", "")
    lines = [
        '"""Clauses imported from the group rule pack snapshot.',
        "",
        "Generated by tools/build_rulepack_catalog.py from",
        "data/rulepack/rulepack_snapshot.json. Do not edit by hand.",
        "",
        f"Source rule pack: {database}",
        f"Source database SHA256: {database_sha}",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
        "RULEPACK_IMPORTED_AS_OF = \"2026-10-26\"",
        "RULEPACK_SOURCE_DATABASE = " + repr(database),
        "RULEPACK_SOURCE_SHA256 = " + repr(database_sha),
        "",
        "RULEPACK_ROWS: tuple[dict[str, Any], ...] = (",
    ]
    for rule in rules:
        rid = rule["rulepack_id"]
        entry = {
            "regulation_id": rid,
            "scene_types": scenes_for(rid),
            "risk_keys": [slug(rid), re.sub(r"[^0-9A-Za-z]+", "_", rid).strip("_").upper()],
            "risk_aliases": aliases_for(rule),
            "standard_name": rule["spec_name"],
            "standard_code": rule["spec_code"],
            "article": f"第{rule['spec_clause']}条",
            "clause_text": " ".join(str(rule["clause_text"]).split()),
            "source_url": f"data/rulepack/rulepack_snapshot.json#{rid}",
            "keywords": [str(k) for k in rule.get("keywords") or []],
            "judge_dimension": rule.get("judge_dimension", ""),
            "judge_boundary": rule.get("judge_boundary") or {},
            "triggers": triggers_for(rule),
            "disposal_suggestion": rule.get("disposal_suggestion", ""),
            "rulepack_version": rule.get("rulepack_version"),
        }
        lines.append("    " + repr(entry) + ",")
    lines.append(")")
    lines.append("")
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {TARGET} with {len(rules)} records")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
