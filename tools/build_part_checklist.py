#!/usr/bin/env python3
"""Generate the scene part-level checklist from data/parts/part_checklist.json.

The rule pack carries 63 items and the main system's 973 are written at the
wrong level ("is the guide rail configured" rather than "is the gate missing").
Real inspection checklists work at a third level: one concrete part, one
defect. That is the granularity the labels use, so the checklist has to speak
that language too.

The generated file is deterministic: the same input produces the same bytes.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
SOURCE = BASE / "data" / "parts" / "part_checklist.json"
TARGET = BASE / "src" / "catalogs" / "part_checklist.py"

HEADER = '''"""Scene part-level inspection items.

Generated by tools/build_part_checklist.py from data/parts/part_checklist.json.
Do not edit by hand; change the source data and rebuild.
"""

from __future__ import annotations

'''


def render(item: dict) -> str:
    part = str(item.get("part") or "").strip()
    check = str(item.get("check") or "").strip()
    standard = str(item.get("standard") or "").strip()
    article = str(item.get("article") or "").strip()
    cite = ""
    if standard and article:
        cite = f"（{standard} {article}）"
    return f"- {part}：{check}{cite}"


def main() -> int:
    if not SOURCE.exists():
        print(f"没有 {SOURCE}", file=sys.stderr)
        return 1
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    lines = [HEADER]
    lines.append("SCENE_PART_LINES: dict[str, list[str]] = {")
    for scene in sorted(data):
        rows = [render(item) for item in data[scene]]
        lines.append(f"    {scene!r}: [")
        for row in rows:
            lines.append(f"        {row!r},")
        lines.append("    ],")
    lines.append("}")
    lines.append("")
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    total = sum(len(v) for v in data.values())
    print(f"写出 {TARGET}：{len(data)} 个场景 {total} 条")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
