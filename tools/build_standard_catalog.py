#!/usr/bin/env python3
"""Generate standard_catalog.py from the fetched standard texts.

A standard is only emitted when its clauses agree with the rule pack on the
clauses both sources cover; that agreement is the evidence that the fetched
text is faithful. The rule pack keeps priority on the clauses it already
provides, because those texts are the ones the project verified by hand.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
OUT = BASE / "data" / "standards"
TARGET = BASE / "src" / "catalogs" / "standard_catalog.py"
sys.path.insert(0, str(BASE / "src"))
sys.path.insert(0, str(BASE))

from catalogs.rulepack_catalog import RULEPACK_ROWS  # noqa: E402

CODE_KEY = lambda s: re.sub(r"[^A-Z0-9]", "", str(s or "").upper())  # noqa: E731
ART_KEY = lambda s: re.sub(r"[^0-9]", "", str(s or ""))  # noqa: E731
NORM = lambda s: re.sub(r"[^0-9A-Za-z一-鿿]", "", str(s or ""))  # noqa: E731


def norm(text: str) -> str:
    return re.sub(r"[^0-9A-Za-z一-鿿]", "", str(text or "")).lower()


def agree(rulepack_text: str, fetched_text: str) -> bool:
    a, b = norm(rulepack_text), norm(fetched_text)
    if not a or not b:
        return False
    if a[:30] in b or b[:30] in a:
        return True
    if len(a) > 12 and a[:12] in b:
        return True
    if len(b) > 12 and b[:12] in a:
        return True
    # 同义措辞：施工电梯 / 施工升降机 等
    synonyms = [("施工电梯", "施工升降机"), ("扣件式", "扣件"), ("挡脚板", "踢脚板"),
                 ("临边", "临边防护"), ("安全网", "密目网")]
    for left, right in synonyms:
        if (left in a and right in b) or (right in a and left in b):
            return True
    return False


def scenes_for(code: str) -> list[str]:
    scenes: set[str] = set()
    for row in RULEPACK_ROWS:
        if CODE_KEY(row["standard_code"]) == CODE_KEY(code):
            scenes.update(row["scene_types"])
    return sorted(scenes) or ["GENERAL_SITE"]


def main() -> int:
    verification = json.loads((OUT / "cross_check.json").read_text(encoding="utf-8")) \
        if (OUT / "cross_check.json").exists() else {}
    entries: list[dict[str, object]] = []
    summary = []
    for path in sorted(OUT.glob("*.json")):
        if path.name in {"source_candidates.json", "download_report.json", "fetch_report.json",
                         "cross_check.json", "standard_catalog_build.json"}:
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        code = data["standard_code"]
        check = verification.get(code, {})
        if not check.get("passed"):
            summary.append({"standard_code": code, "clause_count": data.get("clause_count", 0),
                            "passed": False, "reason": check.get("reason", "未做交叉校验")})
            continue
        scenes = scenes_for(code)
        kept = 0
        for clause in data["clauses"]:
            article = clause["article"]
            text = " ".join(clause["text"].split())
            entries.append({
                "regulation_id": f"STD-{re.sub(r'[^0-9A-Za-z]+', '-', code).strip('-')}-{article.replace('.', '-')}",
                "scene_types": scenes,
                "standard_name": data["standard_name"],
                "standard_code": code,
                "article": f"第{article}条",
                "clause_text": text,
                "source_url": data["source_url"],
                "sha256": data["sha256"],
                "method": data["method"],
                "fetched_at": data.get("fetched_at", ""),
                "cross_checked": True,
                "cross_check_note": check.get("note", ""),
            })
            kept += 1
        summary.append({"standard_code": code, "clause_count": kept, "passed": True,
                        "checked": check.get("checked"), "agreed": check.get("agreed"),
                        "source_url": data["source_url"]})
    lines = [
        '"""Clauses extracted from publicly published full texts of the standards.',
        "",
        "Generated by tools/build_standard_catalog.py. Each standard is only",
        "included when the clauses it shares with the rule pack agree with the",
        "rule pack text; the rule pack wording wins for the clauses it already",
        "covers. The source URL, the SHA256 of the downloaded file and the",
        "extraction method are kept so every clause stays traceable.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
        "STANDARD_CATALOG_VERIFIED_AS_OF = \"2026-10-26\"",
        "",
        "STANDARD_ROWS: tuple[dict[str, Any], ...] = (",
    ]
    for entry in entries:
        lines.append("    " + repr(entry) + ",")
    lines.append(")")
    lines.append("")
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    (OUT / "standard_catalog_build.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"写入 {TARGET}：{len(entries)} 条，来自 {len([s for s in summary if s['passed']])} 部标准")
    for item in summary:
        print(json.dumps(item, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
